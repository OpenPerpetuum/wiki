#!/usr/bin/env python3
"""Generate static/i18n.js from translations/*.json files.

Each JSON file defines one language:
{
  "lang": "fr",
  "name": "Français",
  "ui": { "nav_home": "Accueil", ... },
  "names": { "crude": "Brut", "zone_tm": "Virginie Nouvelle", ... }
}

The generated i18n.js is a self-contained IIFE that defines:
  window.WIKI_I18N      — per-language UI strings
  window.WIKI_NAMES     — per-language game name translations
  window.WIKI_LANGS     — list of available languages [{code, name}]
  window.WIKI_getLang() — current language (from localStorage)
  window.WIKI_setLang() — switch language (saves + applies)
  window.WIKI_applyLang() — swap all tagged elements

Usage:
  python3 tools/gen_i18n.py [translations-dir] [output-file]

  translations-dir  defaults to "translations"
  output-file       defaults to "static/i18n.js"
"""
import json
import os
import sys
from pathlib import Path


def main():
    trans_dir = Path(sys.argv[1] if len(sys.argv) > 1 else "translations")
    out_file = Path(sys.argv[2] if len(sys.argv) > 2 else "static/i18n.js")

    # Read all language JSON files (sorted: en first, then alphabetical)
    langs = []
    for f in sorted(trans_dir.glob("*.json")):
        with open(f, "r", encoding="utf-8") as fh:
            data = json.load(fh)
        if "lang" not in data or "ui" not in data:
            continue
        langs.append(data)

    if not langs:
        print(f"gen_i18n: no valid JSON files found in {trans_dir}/", file=sys.stderr)
        sys.exit(1)

    # Sort: English first (if present), then alphabetical by code
    langs.sort(key=lambda x: (0 if x["lang"] == "en" else 1, x["lang"]))

    # Build the JS output
    lines = []
    lines.append("// AUTO-GENERATED by tools/gen_i18n.py — do not edit by hand.")
    lines.append("// Source: translations/*.json. Re-run `make i18n` after changes.")
    lines.append("(function () {")
    lines.append("    'use strict';")
    lines.append("")

    # WIKI_LANGS: list of available languages
    lines.append("    var LANGS = [")
    for i, l in enumerate(langs):
        comma = "," if i < len(langs) - 1 else ""
        lines.append(f'        {{code:"{l["lang"]}",name:"{l.get("name", l["lang"])}"}}{comma}')
    lines.append("    ];")
    lines.append("")

    # WIKI_I18N: per-language UI strings
    lines.append("    var STRINGS = {")
    for i, l in enumerate(langs):
        comma = "," if i < len(langs) - 1 else ""
        key = l["lang"]
        if '-' in key: key = f'"{key}"'
        lines.append(f'        {key}: {{')
        ui = l["ui"]
        keys = sorted(ui.keys())
        for j, k in enumerate(keys):
            c = "," if j < len(keys) - 1 else ""
            v = ui[k].replace("\\", "\\\\").replace('"', '\\"')
            lines.append(f'            {k}: "{v}"{c}')
        lines.append(f"        }}{comma}")
    lines.append("    };")
    lines.append("")

    # WIKI_NAMES: per-language game name translations
    lines.append("    var NAMES = {")
    for i, l in enumerate(langs):
        comma = "," if i < len(langs) - 1 else ""
        key = l["lang"]
        if '-' in key: key = f'"{key}"'
        lines.append(f'        {key}: {{')
        names = l.get("names", {})
        keys = sorted(names.keys())
        for j, k in enumerate(keys):
            c = "," if j < len(keys) - 1 else ""
            v = names[k].replace("\\", "\\\\").replace('"', '\\"')
            lines.append(f'            "{k}": "{v}"{c}')
        lines.append(f"        }}{comma}")
    lines.append("    };")
    lines.append("")

    # Runtime logic (same as before, but reads from the generated data)
    lines.append("""
    function getLang() {
        try { return localStorage.getItem('wiki-lang') || 'en'; } catch (e) { return 'en'; }
    }

    // Language pages manifest: {"fr": ["/fr/", "/fr/features/faq"], ...}
    // Loaded from /lang-pages.json on startup.
    var LANG_PAGES = null;

    function loadLangPages() {
        try {
            var root = (document.body && document.body.getAttribute('data-root')) || '';
            var path = root.replace(/^https?:\/\/[^\/]+/, '').replace(/\/+$/, '');
            fetch(path + '/lang-pages.json').then(function (r) { return r.ok ? r.json() : null; }).then(function (d) {
                if (d) LANG_PAGES = d;
            }).catch(function () {});
        } catch (e) {}
    }

    // Check if the current page has a translated equivalent in language `l`.
    // Returns the target URL or null.
    var DEFAULT_LANG = LANGS.length > 0 ? LANGS[0].code : 'en';

    function translatedUrl(l) {
        var path = window.location.pathname;
        // Strip the current language prefix if present
        var currentPrefix = '';
        var m = /^\/([a-z]{2,3})/.exec(path);
        if (m && m[1] !== DEFAULT_LANG && LANG_PAGES && LANG_PAGES[m[1]]) {
            currentPrefix = '/' + m[1];
        }
        var basePath = path.replace(currentPrefix, '');

        if (l === DEFAULT_LANG) {
            // Default language: the target is just the base path (no prefix)
            if (currentPrefix && basePath !== path) return basePath;
            return null; // already on the default language
        }

        // Non-default language: check the manifest
        if (!LANG_PAGES || !LANG_PAGES[l]) return null;
        var target = '/' + l + basePath;
        var pages = LANG_PAGES[l];
        for (var i = 0; i < pages.length; i++) {
            if (pages[i] === target || pages[i] + '/' === target) return target;
        }
        return null;
    }

    function setLang(l) {
        try { localStorage.setItem('wiki-lang', l); } catch (e) {}
        applyLang(l);
        // If a translated version of this page exists, navigate to it
        var url = translatedUrl(l);
        if (url && url !== window.location.pathname) {
            window.location.href = url;
        }
    }

    // Swap all translatable chrome strings + game names.
    // Elements are tagged:
    //   data-i18n="key"        → textContent (UI chrome)
    //   data-i18n-html="key"   → innerHTML (UI strings with markup)
    //   data-i18n-ph="key"     → placeholder attribute
    //   data-i18n-aria="key"   → aria-label + title attributes
    //   data-def="slug"        → textContent (game name, looked up in NAMES)
    function applyLang(l) {
        var s = STRINGS[l];
        if (!s) l = 'en', s = STRINGS.en;
        var n = NAMES[l] || {};
        document.documentElement.setAttribute('lang', l);

        // UI chrome: text content
        var els = document.querySelectorAll('[data-i18n]');
        for (var i = 0; i < els.length; i++) {
            var key = els[i].getAttribute('data-i18n');
            if (s[key] != null) els[i].textContent = s[key];
        }
        // UI chrome: innerHTML (strings with markup)
        var htmls = document.querySelectorAll('[data-i18n-html]');
        for (var h = 0; h < htmls.length; h++) {
            var hk = htmls[h].getAttribute('data-i18n-html');
            if (s[hk] != null) htmls[h].innerHTML = s[hk];
        }
        // UI chrome: placeholder
        var phs = document.querySelectorAll('[data-i18n-ph]');
        for (var j = 0; j < phs.length; j++) {
            var pk = phs[j].getAttribute('data-i18n-ph');
            if (s[pk] != null) phs[j].placeholder = s[pk];
        }
        // UI chrome: aria-label + title
        var arias = document.querySelectorAll('[data-i18n-aria]');
        for (var k = 0; k < arias.length; k++) {
            var ak = arias[k].getAttribute('data-i18n-aria');
            if (s[ak] != null) {
                arias[k].setAttribute('aria-label', s[ak]);
                arias[k].setAttribute('title', s[ak]);
            }
        }
        // Game names: elements tagged with data-def
        var defs = document.querySelectorAll('[data-def]');
        for (var d = 0; d < defs.length; d++) {
            var dk = defs[d].getAttribute('data-def');
            if (n[dk] != null) defs[d].textContent = n[dk];
        }
        // Page title + H1: if the body has data-page-def, update both
        var body = document.body;
        if (body) {
            var pd = body.getAttribute('data-page-def');
            if (pd && n[pd] != null) {
                var suffix = document.title.indexOf(' | ') !== -1 ? ' | Open Perpetuum Wiki' : '';
                document.title = n[pd] + suffix;
                var h1 = document.querySelector('h1');
                if (h1) h1.textContent = n[pd];
            }
        }
        // Update WIKI_UI (used by search.js, zone-map.js)
        if (window.WIKI_UI) {
            window.WIKI_UI.searchNoResults = s.search_no_results || '';
            window.WIKI_UI.searchUnavailable = s.search_unavailable || '';
            window.WIKI_UI.pagesFoundOne = s.search_pages_found_one || '';
            window.WIKI_UI.pagesFoundMany = s.search_pages_found_many || '';
            window.WIKI_UI.updateAvailable = s.update_available || '';
            window.WIKI_UI.zonemapModeHeight = s.zonemap_mode_height || '';
            window.WIKI_UI.zonemapModeColor = s.zonemap_mode_color || '';
        }
        // Lang menu active state
        var btns = document.querySelectorAll('#lang-menu button[data-lang]');
        for (var m = 0; m < btns.length; m++) {
            btns[m].setAttribute('aria-pressed', btns[m].getAttribute('data-lang') === l ? 'true' : 'false');
        }
    }

    // Populate the language menu from LANGS (one button per available language).
    // The menu is empty in the HTML; this runs once on load.
    function buildLangMenu() {
        var menu = document.getElementById('lang-menu');
        if (!menu || menu.children.length > 0) return; // already populated
        var cur = getLang();
        for (var i = 0; i < LANGS.length; i++) {
            var b = document.createElement('button');
            b.type = 'button';
            b.setAttribute('role', 'menuitem');
            b.setAttribute('data-lang', LANGS[i].code);
            b.setAttribute('aria-pressed', LANGS[i].code === cur ? 'true' : 'false');
            b.textContent = LANGS[i].code.toUpperCase() + ' \u2014 ' + LANGS[i].name;
            (function (btn) {
                btn.addEventListener('click', function () {
                    setLang(btn.getAttribute('data-lang'));
                    var m = document.getElementById('lang-menu');
                    if (m) m.classList.remove('open');
                    var t = document.getElementById('lang-toggle');
                    if (t) t.setAttribute('aria-expanded', 'false');
                });
            })(b);
            menu.appendChild(b);
        }
    }

    window.WIKI_I18N = STRINGS;
    window.WIKI_NAMES = NAMES;
    window.WIKI_LANGS = LANGS;
    window.WIKI_getLang = getLang;
    window.WIKI_setLang = setLang;
    window.WIKI_applyLang = applyLang;

    if (document.readyState === 'loading') {
        document.addEventListener('DOMContentLoaded', function () { loadLangPages(); buildLangMenu(); applyLang(getLang()); });
    } else {
        loadLangPages();
        buildLangMenu();
        applyLang(getLang());
    }
""")
    lines.append("})();")
    lines.append("")

    # Write the output
    out_file.parent.mkdir(parents=True, exist_ok=True)
    with open(out_file, "w", encoding="utf-8") as f:
        f.write("\n".join(lines))

    # Summary
    total_names = sum(len(l.get("names", {})) for l in langs)
    print(f"gen_i18n: {len(langs)} languages, {total_names} name translations → {out_file}")


if __name__ == "__main__":
    main()
